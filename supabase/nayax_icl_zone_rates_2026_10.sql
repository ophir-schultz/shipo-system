-- Nayax freight sell card: the ICL zone matrix.
--
-- Source: "ICL Shipping Rates.xlsx", sheet 'NEW ICL_MAY 19 2026', whose own
-- header reads "EFFECTIVE - MAY 19 / ADDITIONAL 3% / UPS". ICL is Nayax's
-- representative, and per Ophir (2026-10-15) these are "the shipping rates that
-- we are charging ICL" -- the SELL side. Cost stays shipments.actual_cost, which
-- is the cheaper ShipStation Ground Saver figure. The margin is the gap, and
-- that gap is the point of this file: it was invisible before.
--
-- WHY THIS SHEET AND NOT 'UPS PRICELISTICL.'
-- Those two sheets are not independent price lists. Verified cell by cell:
-- 'NEW ICL_MAY 19 2026' equals 'UPS PRICELISTICL.' (headed "ICL CLIENTS /
-- ORCAM") multiplied by exactly 1.03 across all 140 overlapping cells, worst
-- absolute difference 0.000000. Combined with this sheet's own "ADDITIONAL 3%"
-- and "EFFECTIVE - MAY 19" header, the ORCAM-labelled sheet is the pre-May-19
-- price and this one is the current one. Do not load both.
--
-- WHY BLANKET carrier/service ('' / '')
-- pickZoneCell (zones.ts:291-299) treats a row with empty carrier AND empty
-- service as covering every carrier, with any carrier-specific row overriding
-- it. Nayax shipment rows carry 'UPS', blank, and Ground Saver spellings
-- inconsistently, and a carrier-specific card that fails to match does NOT fall
-- back to another carrier's cell -- zones.ts:321-324 refuses, deliberately,
-- because billing from the wrong agreement is worse than not billing. Blanket
-- is the shape that cannot miss on a spelling.
--
-- The delete below removes only the BLANKET card. Any carrier-specific Nayax
-- rows are left alone precisely because they outrank this card by design;
-- silently deleting them here would re-price those lanes.
--
-- PRECISION. The sheet carries 4 decimal places; client_zone_rates.rate is
-- numeric(10,2). 693 of the 700 source cells therefore round. The rounding is
-- done HALF_UP in the generator rather than left to the column's coercion, so
-- the numbers in this file are exactly the numbers that land -- at most half a
-- cent per label away from the sheet.
--
-- PRECONDITION -- READ THIS BEFORE BELIEVING THE CARD WORKS.
-- A zone cell is only ever consulted for a shipment whose zone is resolved.
-- resolveZone (zones.ts:155) derives zone from the recipient ZIP against
-- clients.origin_zip and the zone_chart table. If Nayax has no origin_zip, or
-- zone_chart is unpopulated for that origin, every lookup misses and these 800
-- rows are inert -- revenue stays unknown and nothing says why. The trailing
-- query checks this; do not skip it.
--
-- NOT the ledger. client_zone_rates feeds billing/calculator.ts and
-- billing/recalculate.ts, which write shipments.client_rate and profit_loss,
-- which is what profit-rollup.ts sums for the dashboard, Reports and Statements.
-- The ledger's charges table takes shipping revenue from the
-- client_warehouse_rates 'shipping' line instead, and Nayax's is at_cost
-- (rate null), so the ledger will book zero freight margin for Nayax while the
-- dashboard books the real one. That disagreement is pre-existing and is NOT
-- resolved by this file. See the note at the end.
--
-- Safe to run more than once: it replaces the blanket card each time.

