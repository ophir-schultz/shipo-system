-- 2. THE PRECONDITION. If can_resolve_zone is 0 the 800 cells above are inert:
--    no origin_zip or no zone_chart means resolveZone never returns a zone and
--    the matrix is never consulted. Fix that before expecting any margin.
select
  c.name,
  c.origin_zip,
  (select count(*) from zone_chart
    where origin_prefix = left(coalesce(c.origin_zip,''),3)) as zone_chart_rows,
  count(s.id)                                    as shipments,
  count(s.zone)                                  as with_zone_resolved,
  count(s.weight)                                as with_weight,
  count(s.actual_cost)                           as with_cost,
  count(s.client_rate)                           as with_client_rate,
  case when c.origin_zip is null or c.origin_zip = '' then 0
       when (select count(*) from zone_chart
              where origin_prefix = left(c.origin_zip,3)) = 0 then 0
       else 1 end                                as can_resolve_zone
from clients c
left join shipments s on s.client_id = c.id
where c.name ilike '%nayax%'
group by c.id, c.name, c.origin_zip;

-- 3. The margin this file exists to expose, once a recalculation has run.
--    Before: revenue = cost on every Nayax label and profit is 0.00 by
--    construction. After: revenue is the ICL cell, cost is the Ground Saver
--    actual, profit is the gap.
select
  count(*)                                       as priced_shipments,
  round(sum(s.client_rate), 2)                   as revenue,
  round(sum(s.actual_cost), 2)                   as cost,
  round(sum(s.client_rate) - sum(s.actual_cost), 2) as profit,
  round(100 * (sum(s.client_rate) - sum(s.actual_cost))
            / nullif(sum(s.client_rate), 0), 2)  as margin_pct
from shipments s join clients c on c.id = s.client_id
where c.name ilike '%nayax%'
  and s.client_rate is not null and s.actual_cost is not null;

